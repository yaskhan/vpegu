}

// generate_helper_methods generates utility methods
fn generate_helper_methods() string {
	return "
// match_literal matches a literal string
fn (mut p PackratParser) match_literal(pos int, literal string) ParseResult {
    if pos + literal.len > p.input.len {
        return ParseResult{false, \"\", pos}
    }
    if p.input[pos..pos + literal.len] == literal {
        return ParseResult{true, literal, pos + literal.len}
    }
    return ParseResult{false, \"\", pos}
}
"
}

